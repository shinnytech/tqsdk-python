def _publish_skill_zips(app, exception):
    """Build downloads in the output tree, including on incremental builds."""
    if exception is not None or app.builder.format != 'html':
        return
    skills_dir = DOC_DIR / 'ai_editor' / 'skills'
    download_dir = Path(app.outdir) / 'ai_editor' / 'skills'
    download_dir.mkdir(parents=True, exist_ok=True)
    for entry in sorted(skills_dir.iterdir()):
        # Preserve historical download URLs, including reference-only bundles.
        if entry.is_dir() and not entry.name.startswith('.') and entry.name != '__pycache__':
            with ZipFile(download_dir / (entry.name + '.zip'), 'w', ZIP_DEFLATED) as archive:
                for source in sorted(entry.rglob('*')):
                    relative = source.relative_to(entry)
                    if (not source.is_file() or
                            any(part.startswith('.') or part == '__pycache__' for part in relative.parts) or
                            source.suffix in {'.pyc', '.pyo', '.zip'}):
                        continue
                    archive.write(source, source.relative_to(skills_dir).as_posix())

def setup(app):
    # The historical notebook declares ipython2; display it without executing it.
    app.add_lexer('ipython2', IPython3Lexer)
    if googleanalytics_enabled:
        app.add_js_file("baidu.js")
    app.add_search_language(TqSdkSearchChinese)
    app.connect('build-finished', _publish_skill_zips)

